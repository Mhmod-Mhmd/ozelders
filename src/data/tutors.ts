import {
  type Availability,
  type AvailabilityPeriod,
  type Tutor,
  type Weekday,
} from '@/features/tutors/types/tutor.types';

const WEEKDAYS: Weekday[] = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
const PERIODS: AvailabilityPeriod[] = [
  'morning',
  'afternoon',
  'evening',
  'night',
];

/** Deterministic, believable weekly availability derived from a seed. */
function buildAvailability(seed: number): Availability {
  const result = {} as Availability;
  WEEKDAYS.forEach((day, d) => {
    const periods: AvailabilityPeriod[] = [];
    PERIODS.forEach((period, p) => {
      if ((seed * 13 + d * 7 + p * 11) % 10 > 3) periods.push(period);
    });
    result[day] = periods;
  });
  return result;
}

